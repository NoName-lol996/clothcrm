const TODAY = new Date();

/** n 天前 */
function daysAgo(n: number): string {
  const d = new Date(TODAY);
  d.setDate(d.getDate() - n);
  return toDateKey(d);
}

/** n 天后 */
function daysLater(n: number): string {
  return daysAgo(-n);
}

